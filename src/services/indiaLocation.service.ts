// In-memory cache for PIN lookups
const pincodeCache: Record<string, PincodeLookupResult> = {};

export function getIndianStates(): string[] {
  return Object.keys(INDIAN_STATES_DISTRICTS).sort();
}

export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return [];
  // Case-insensitive lookup
  const key = Object.keys(INDIAN_STATES_DISTRICTS).find(
    (k) => k.toLowerCase() === stateName.trim().toLowerCase()
  );
  return key ? INDIAN_STATES_DISTRICTS[key].sort() : [];
}

export function findMatchingState(name: string): string | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  return Object.keys(INDIAN_STATES_DISTRICTS).find(
    (k) => k.toLowerCase() === clean || clean.includes(k.toLowerCase()) || k.toLowerCase().includes(clean)
  );
}

export function findMatchingDistrict(districtName: string, stateName?: string): string | undefined {
  if (!districtName) return undefined;
  const clean = districtName.trim().toLowerCase();

  const candidates = stateName ? getDistrictsForState(stateName) : Object.values(INDIAN_STATES_DISTRICTS).flat();
  return candidates.find((d) => {
    const dClean = d.toLowerCase();
    return dClean === clean || dClean.includes(clean) || clean.includes(dClean);
  });
}

export async function lookupIndiaPincode(pincode: string): Promise<PincodeLookupResult> {
  const cleanPin = pincode.replace(/\D/g, '').trim();
  if (cleanPin.length !== 6) {
    return {
      success: false,
      pincode: cleanPin,
      postOffices: [],
      message: 'PIN code must be exactly 6 digits',
    };
  }

  if (pincodeCache[cleanPin]) {
    return pincodeCache[cleanPin];
  }

  try {
    const res = await fetch(`https://api.postalpincode.in/pincode/${cleanPin}`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);

    const data = await res.json();
    if (Array.isArray(data) && data[0] && data[0].Status === 'Success' && Array.isArray(data[0].PostOffice)) {
      const offices = data[0].PostOffice;
      const rawDistrict = offices[0]?.District || '';
      const rawState = offices[0]?.State || '';

      // Match with canonical states & districts
      const matchedState = findMatchingState(rawState) || rawState;
      const matchedDistrict = findMatchingDistrict(rawDistrict, matchedState) || rawDistrict;

      const postOffices: string[] = Array.from<string>(
        new Set(offices.map((o: any) => String(o.Name || '').trim()))
      ).filter(Boolean);

      const result: PincodeLookupResult = {
        success: true,
        pincode: cleanPin,
        state: matchedState,
        district: matchedDistrict,
        postOffices,
      };

      pincodeCache[cleanPin] = result;
      return result;
    }

    return {
      success: false,
      pincode: cleanPin,
      postOffices: [],
      message: 'No post offices found for this PIN code',
    };
  } catch (err: any) {
    console.warn(`PIN code API lookup error for ${cleanPin}:`, err);
    return {
      success: false,
      pincode: cleanPin,
      postOffices: [],
      message: 'Could not fetch PIN code details from India Post API',
    };
  }
}
